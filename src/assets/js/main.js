let openDropdownId = null;
function toggleDropdown(id){
  const el = document.getElementById(id);
  if(!el) return;
  const isOpen = el.classList.contains('open');
  closeAllDropdowns();
  if(!isOpen){
    el.classList.add('open');
    el.querySelector('.navtrigger').setAttribute('aria-expanded','true');
    openDropdownId = id;
  }
}
function closeAllDropdowns(){
  document.querySelectorAll('.navitem.open').forEach(el => {
    el.classList.remove('open');
    el.querySelector('.navtrigger').setAttribute('aria-expanded','false');
  });
  openDropdownId = null;
}
document.addEventListener('click', (e) => {
  if(openDropdownId && !e.target.closest('#' + openDropdownId)) closeAllDropdowns();
});
document.addEventListener('keydown', (e) => { if(e.key === 'Escape'){ closeAllDropdowns(); toggleMobileNav(false); } });

function toggleMobileNav(open){
  const nav = document.getElementById('mobileNav');
  const overlay = document.getElementById('mobileNavOverlay');
  if(!nav || !overlay) return;
  nav.classList.toggle('open', open);
  overlay.style.opacity = open ? '1' : '0';
  overlay.style.pointerEvents = open ? 'auto' : 'none';
  document.body.style.overflow = open ? 'hidden' : '';
}
function toggleMnavPanel(btn){
  const expanded = btn.getAttribute('aria-expanded') === 'true';
  btn.setAttribute('aria-expanded', String(!expanded));
}

