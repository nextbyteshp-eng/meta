/* ==========================================================================
   HERO CAROUSEL (home page only) — slides are rendered from CONTENT.home.hero_slides
   (loaded from content.js, generated by the build from content/home.json),
   so adding/editing/removing a slide from the admin panel just works.
   ========================================================================== */
(function initHero(){
  const container = document.getElementById('heroSlides');
  if(!container) return;

  const slidesData = (typeof CONTENT !== 'undefined' && CONTENT.home && CONTENT.home.hero_slides) || [];
  if(!slidesData.length) return;

  container.innerHTML = slidesData.map((s, i) => `
    <div class="hero-slide${i===0?' active':''}">
      <div class="slide-bg" style="background:#0c1a08 url('${s.imagen}') center/cover no-repeat;"></div>
      <div class="wrap">
        <div class="slide-content">
          <span class="eyebrow">${s.eyebrow || ''}</span>
          <h1>${s.titulo || ''}</h1>
          <p>${s.texto || ''}</p>
          <a href="${s.boton_link || '#'}" class="btn btn-fill">${s.boton_texto || ''}</a>
        </div>
      </div>
    </div>
  `).join('');

  const slides = document.querySelectorAll('.hero-slide');
  let heroIndex = 0;
  let heroTimer = null;

  function renderHeroDots(){
    const dotsEl = document.getElementById('heroDots');
    if(!dotsEl) return;
    dotsEl.innerHTML = Array.from(slides).map((_, i) =>
      `<button class="hero-dot${i===0?' active':''}" aria-label="Ir a la imagen ${i+1}" onclick="heroGoTo(${i})"></button>`
    ).join('');
  }
  window.heroGoTo = function(i){
    slides[heroIndex].classList.remove('active');
    document.querySelectorAll('.hero-dot')[heroIndex]?.classList.remove('active');
    heroIndex = (i + slides.length) % slides.length;
    slides[heroIndex].classList.add('active');
    document.querySelectorAll('.hero-dot')[heroIndex]?.classList.add('active');
  };
  window.heroNext = function(){ heroGoTo(heroIndex + 1); };
  window.heroPrev = function(){ heroGoTo(heroIndex - 1); };

  function startAutoplay(){ if(!reduceMotion) heroTimer = setInterval(heroNext, 5500); }
  const heroEl = document.querySelector('.hero');
  if(heroEl){
    heroEl.addEventListener('mouseenter', () => clearInterval(heroTimer));
    heroEl.addEventListener('mouseleave', startAutoplay);

    let touchStartX = 0, touchStartY = 0, touchActive = false;
    heroEl.addEventListener('touchstart', (e) => {
      touchStartX = e.touches[0].clientX;
      touchStartY = e.touches[0].clientY;
      touchActive = true;
      clearInterval(heroTimer);
    }, { passive: true });
    heroEl.addEventListener('touchend', (e) => {
      if(!touchActive) return;
      touchActive = false;
      const dx = e.changedTouches[0].clientX - touchStartX;
      const dy = e.changedTouches[0].clientY - touchStartY;
      if(Math.abs(dx) > 40 && Math.abs(dx) > Math.abs(dy)){
        if(dx < 0) heroNext(); else heroPrev();
      }
      startAutoplay();
    }, { passive: true });
  }
  renderHeroDots();
  startAutoplay();
})();

/* ==========================================================================
   PACK BUILDER (meta pages: definir.html / mantener.html / construir.html)
   The page sets <body data-meta="definir"> — that fixes the meta for this
   page's numbered packs. The "Armá tu pack" custom option still lets the
   shopper pick a meta per dish, independent of the page they arrived on.
   ========================================================================== */
(function initPacks(){
  const grid = document.getElementById('packsGrid');
  if(!grid) return;

  const PAGE_META = document.body.dataset.meta || 'mantener';

  const state = {
    meta: PAGE_META,
    packType: null,       // '7' | '14' | '28' | 'custom'
    fixedCart: {},          // dishId -> qty
    customCart: {},          // "dishId:metaKey" -> qty
    customView: {},           // dishId -> currently viewed metaKey (custom mode)
  };

  function metaIconPath(key){
    if(key==='definir')   return '<path d="M4 15l6-6 4 4 6-8"/><path d="M14 5h6v6"/>';
    if(key==='construir')  return '<path d="M4 19l6-6 4 4 6-8"/><path d="M20 3v6h-6"/>';
    return '<path d="M4 12h16"/><path d="M8 8l-4 4 4 4"/><path d="M16 8l4 4-4 4"/>';
  }

  function scaleDish(dish, metaKey){
    // Each dish carries its real macros per meta directly (set from the
    // admin panel / content/dishes/*.json), using the Spanish field names
    // the CMS shows (proteinas/carbohidratos/grasas) — translate them to
    // the short names the rest of this file already uses (p/c/f).
    const m = dish[metaKey] || dish.mantener || {};
    return { kcal: m.kcal || 0, p: m.proteinas || 0, c: m.carbohidratos || 0, f: m.grasas || 0 };
  }

  function initPackPrices(){
    ['7','14','28'].forEach(n => {
      const unit = PRICING.packs[n].unit;
      const total = unit * Number(n);
      const priceEl = document.querySelector(`[data-price="${n}"]`);
      const unitEl = document.querySelector(`[data-unit="${n}"]`);
      if(priceEl) priceEl.textContent = `$ ${fmt(total)}`;
      if(unitEl) unitEl.textContent = `$ ${fmt(unit)} c/u`;
    });
    const customEl = document.getElementById('customFromPrice');
    if(customEl) customEl.textContent = `Desde $ ${fmt(PRICING.individual)} c/u`;
  }

  window.selectPack = function(type){
    state.packType = type;
    state.fixedCart = {};
    state.customCart = {};
    state.customView = {};

    document.querySelectorAll('.pack-card').forEach(c => c.classList.toggle('active', c.dataset.pack === type));

    document.getElementById('builder').classList.add('open');
    document.getElementById('checkout').classList.remove('open');

    document.getElementById('builderTitle').textContent = type === 'custom'
      ? 'Armá tu pack personalizado'
      : `Elegí tus ${type} viandas`;

    renderMenu();
    updateSummary();

    document.getElementById('builder').scrollIntoView({ behavior: reduceMotion ? 'auto' : 'smooth', block: 'start' });
  };

  function renderMenu(){
    const container = document.getElementById('menuContainer');
    const isCustom = state.packType === 'custom';

    container.innerHTML = CATEGORIES.map(cat => `
      <div class="menu-cat">
        <div class="menu-cat-title">${cat}</div>
        <div class="menu-grid">
          ${DISHES.filter(d => d.cat === cat).map(d => renderDishCard(d, isCustom)).join('')}
        </div>
      </div>
    `).join('');

    updateBuilderProgress();
  }

  function renderDishCard(dish, isCustom){
    const viewMeta = isCustom ? (state.customView[dish.id] || state.meta) : state.meta;
    const m = scaleDish(dish, viewMeta);
    const qty = isCustom ? (state.customCart[`${dish.id}:${viewMeta}`] || 0) : (state.fixedCart[dish.id] || 0);

    const target = Number(state.packType);
    const total = computeFixedCount();
    const plusDisabled = !isCustom && total >= target;
    const unitPrice = isCustom ? PRICING.individual : PRICING.packs[state.packType].unit;

    const pillsHtml = isCustom ? `
      <div class="meta-pills">
        ${['definir','mantener','construir'].map(mk => `
          <button class="meta-pill${viewMeta===mk?' active':''}" data-m="${mk}" onclick="setCustomView('${dish.id}','${mk}')">${META_FACTORS[mk].label}</button>
        `).join('')}
      </div>` : '';

    const minusFn = isCustom ? `changeCustomQty('${dish.id}','${viewMeta}',-1)` : `changeFixedQty('${dish.id}',-1)`;
    const plusFn = isCustom ? `changeCustomQty('${dish.id}','${viewMeta}',1)` : `changeFixedQty('${dish.id}',1)`;

    return `
      <div class="dish-card">
        <div class="dish-card-top">
          <h4>${dish.name}</h4>
          <span class="dish-price">$ ${fmt(unitPrice)}</span>
        </div>
        <p>${dish.desc}</p>
        ${pillsHtml}
        <div class="dish-macros">
          <span class="kcal">${m.kcal} kcal</span><span>·</span>
          <span class="mp">P ${m.p}g</span><span class="mc">C ${m.c}g</span><span class="mf">G ${m.f}g</span>
        </div>
        <div class="dish-foot">
          <span></span>
          <div class="stepper">
            <button onclick="${minusFn}" aria-label="Quitar" ${qty===0?'disabled':''}>−</button>
            <span class="stepper-qty">${qty}</span>
            <button onclick="${plusFn}" aria-label="Agregar" ${plusDisabled?'disabled':''}>+</button>
          </div>
        </div>
      </div>`;
  }

  window.setCustomView = function(dishId, metaKey){
    state.customView[dishId] = metaKey;
    renderMenu();
  };

  function computeFixedCount(){ return Object.values(state.fixedCart).reduce((a,b) => a+b, 0); }
  function computeCustomCount(){ return Object.values(state.customCart).reduce((a,b) => a+b, 0); }

  window.changeFixedQty = function(dishId, delta){
    const target = Number(state.packType);
    const total = computeFixedCount();
    if(delta > 0 && total >= target) return;
    const next = Math.max(0, (state.fixedCart[dishId] || 0) + delta);
    if(next === 0) delete state.fixedCart[dishId]; else state.fixedCart[dishId] = next;
    renderMenu();
    updateSummary();
  };

  window.changeCustomQty = function(dishId, metaKey, delta){
    const key = `${dishId}:${metaKey}`;
    const next = Math.max(0, (state.customCart[key] || 0) + delta);
    if(next === 0) delete state.customCart[key]; else state.customCart[key] = next;
    renderMenu();
    updateSummary();
  };

  function updateBuilderProgress(){
    const el = document.getElementById('builderProgress');
    if(state.packType === 'custom'){
      const n = computeCustomCount();
      el.innerHTML = `<strong>${n}</strong> vianda${n===1?'':'s'} agregada${n===1?'':'s'}`;
    } else {
      const target = Number(state.packType);
      const n = computeFixedCount();
      el.innerHTML = `<strong>${n} / ${target}</strong> viandas seleccionadas`;
    }
  }

  function computeTotals(){
    let price = 0, kcal = 0, p = 0, c = 0, f = 0;
    if(state.packType === 'custom'){
      Object.entries(state.customCart).forEach(([key, qty]) => {
        const [dishId, metaKey] = key.split(':');
        const m = scaleDish(DISH_MAP[dishId], metaKey);
        price += PRICING.individual * qty;
        kcal += m.kcal*qty; p += m.p*qty; c += m.c*qty; f += m.f*qty;
      });
    } else if(state.packType){
      const target = Number(state.packType);
      const count = computeFixedCount();
      Object.entries(state.fixedCart).forEach(([dishId, qty]) => {
        const m = scaleDish(DISH_MAP[dishId], state.meta);
        kcal += m.kcal*qty; p += m.p*qty; c += m.c*qty; f += m.f*qty;
      });
      if(count === target) price = target * PRICING.packs[target].unit;
    }
    return { price, kcal, p, c, f };
  }

  function updateSummary(){
    updateBuilderProgress();
    const box = document.getElementById('summaryContent');
    const totals = computeTotals();
    const isCustom = state.packType === 'custom';
    const target = Number(state.packType);
    const count = isCustom ? computeCustomCount() : computeFixedCount();

    let linesHtml = '';
    if(count === 0){
      linesHtml = `<p class="summary-empty">Todavía no elegiste ninguna vianda.</p>`;
    } else if(isCustom){
      linesHtml = Object.entries(state.customCart).filter(([,q]) => q>0).map(([key, qty]) => {
        const [dishId, metaKey] = key.split(':');
        return `<div class="summary-line"><span class="sl-name">${DISH_MAP[dishId].name} <span class="sl-tag">${META_FACTORS[metaKey].label}</span></span><span>x${qty}</span></div>`;
      }).join('');
    } else {
      linesHtml = Object.entries(state.fixedCart).filter(([,q]) => q>0).map(([dishId, qty]) =>
        `<div class="summary-line"><span class="sl-name">${DISH_MAP[dishId].name}</span><span>x${qty}</span></div>`
      ).join('');
      if(count < target){
        linesHtml += `<p class="summary-empty" style="margin-top:10px">Sumá ${target-count} vianda${target-count===1?'':'s'} más para completar tu pack.</p>`;
      }
    }
    box.innerHTML = linesHtml;

    const canContinue = isCustom ? count > 0 : count === target;
    document.getElementById('continueBtn').disabled = !canContinue;

    document.getElementById('orderSummary').querySelector('.summary-totals')?.remove();
    document.getElementById('orderSummary').querySelector('.summary-kcal')?.remove();
    if(canContinue){
      box.insertAdjacentHTML('afterend', `
        <div class="summary-totals"><span class="st-label">Total</span><span class="st-value">$ ${fmt(totals.price)}</span></div>
        <div class="summary-kcal">${fmt(totals.kcal)} kcal aprox. totales</div>`);
    }

    if(!canContinue) document.getElementById('checkout').classList.remove('open');
  }

  window.openCheckout = function(){
    document.getElementById('checkout').classList.add('open');
    validateCheckout();
    document.getElementById('checkout').scrollIntoView({ behavior: reduceMotion ? 'auto' : 'smooth', block: 'start' });
  };

  window.onDeliveryChange = function(){
    const isShip = document.getElementById('dvShip').checked;
    document.getElementById('addressField').style.display = isShip ? 'flex' : 'none';
    validateCheckout();
  };

  window.validateCheckout = function(){
    const name = document.getElementById('ckName').value.trim();
    const phone = document.getElementById('ckPhone').value.trim();
    const delivery = document.querySelector('input[name="delivery"]:checked');
    const day = document.getElementById('ckDay').value;
    const payment = document.querySelector('input[name="payment"]:checked');
    const address = document.getElementById('ckAddress').value.trim();

    let ok = name && phone && delivery && day && payment;
    if(delivery && delivery.value === 'envio' && !address) ok = false;

    document.getElementById('sendOrderBtn').disabled = !ok;
  };

  function buildOrderMessage(){
    const lines = [];
    lines.push('¡Hola META! 👋 Quiero hacer este pedido:');
    lines.push('');

    if(state.packType === 'custom'){
      lines.push('📦 Pack: Personalizado');
      lines.push('');
      lines.push('Detalle:');
      Object.entries(state.customCart).filter(([,q]) => q>0).forEach(([key, qty]) => {
        const [dishId, metaKey] = key.split(':');
        lines.push(`• ${DISH_MAP[dishId].name} (${META_FACTORS[metaKey].label}) x${qty}`);
      });
    } else {
      lines.push(`🎯 Meta: ${META_FACTORS[state.meta].label}`);
      lines.push(`📦 Pack: ${state.packType} viandas`);
      lines.push('');
      lines.push('Detalle:');
      Object.entries(state.fixedCart).filter(([,q]) => q>0).forEach(([dishId, qty]) => {
        lines.push(`• ${DISH_MAP[dishId].name} x${qty}`);
      });
    }

    const totals = computeTotals();
    lines.push('');
    lines.push('──────────────');
    lines.push(`💰 Total: $ ${fmt(totals.price)}`);
    lines.push(`🔥 Calorías aprox: ${fmt(totals.kcal)} kcal`);
    lines.push('');

    const delivery = document.querySelector('input[name="delivery"]:checked').value;
    lines.push('🚚 Entrega: ' + (delivery === 'envio' ? 'Envío a domicilio ($5.000)' : 'Retiro en Necochea 444, Pilar'));
    if(delivery === 'envio'){
      lines.push('📍 Dirección: ' + document.getElementById('ckAddress').value.trim());
    }
    lines.push('🗓️ Día preferido: ' + document.getElementById('ckDay').value);
    lines.push('💳 Pago: ' + document.querySelector('input[name="payment"]:checked').value);
    lines.push('');
    lines.push('👤 Nombre: ' + document.getElementById('ckName').value.trim());
    lines.push('📞 Teléfono: ' + document.getElementById('ckPhone').value.trim());
    const notes = document.getElementById('ckNotes').value.trim();
    if(notes) lines.push('📝 Comentarios: ' + notes);
    const coupon = document.getElementById('ckCoupon')?.value.trim();
    if(coupon) lines.push('🏷️ Cupón: ' + coupon);

    return lines.join('\n');
  }

  window.sendOrder = function(){
    if(document.getElementById('sendOrderBtn').disabled) return;
    const text = encodeURIComponent(buildOrderMessage());
    window.open(`https://wa.me/${PHONE_PRIMARY}?text=${text}`, '_blank');
  };

  initPackPrices();
})();

